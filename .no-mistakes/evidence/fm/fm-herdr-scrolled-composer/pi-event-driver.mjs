import {mkdirSync,writeFileSync,copyFileSync,symlinkSync,existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const root=process.cwd(), fixture=resolve('.r/event-repo'), home=resolve('.r/event-home'), agentDir=resolve('.r/event-agent');
for(const p of [fixture+'/.pi/extensions',home+'/state',home+'/config',agentDir])mkdirSync(p,{recursive:true});
copyFileSync(process.env.PHASE_BASE ? '.r/base-branch.ts' : '.pi/extensions/fm-branch-supervision.ts',fixture+'/.pi/extensions/fm-branch-supervision.ts');
copyFileSync('.pi/extensions/fm-primary-pi-watch.ts',fixture+'/.pi/extensions/fm-primary-pi-watch.ts');
if(!existsSync(fixture+'/.pi/extensions/lib'))symlinkSync(root+'/.pi/extensions/lib',fixture+'/.pi/extensions/lib');
if(!existsSync(fixture+'/node_modules'))symlinkSync(root+'/.r/pi99/node_modules',fixture+'/node_modules');
process.env.FM_HOME=home;process.env.FM_ROOT_OVERRIDE=root;process.env.PI_CODING_AGENT_DIR=agentDir;
writeFileSync(home+'/state/.lock',process.pid+'\n');
const pkg=resolve('.r/pi99/node_modules/@earendil-works/pi-coding-agent');
const {DefaultResourceLoader,ModelRuntime,SessionManager,SettingsManager,createAgentSession}=await import(pathToFileURL(pkg+'/dist/index.js'));
const settings=SettingsManager.create(fixture,agentDir);
const loader=new DefaultResourceLoader({cwd:fixture,agentDir,settingsManager:settings,additionalExtensionPaths:[fixture+'/.pi/extensions/fm-branch-supervision.ts',fixture+'/.pi/extensions/fm-primary-pi-watch.ts'],noSkills:true,noPromptTemplates:true,noThemes:true,noContextFiles:true});
await loader.reload();
const loaded=loader.getExtensions();if(loaded.errors.length)throw new Error(JSON.stringify(loaded.errors));
const runtime=await ModelRuntime.create({authPath:agentDir+'/auth.json',modelsPath:agentDir+'/models.json'});
const {session}=await createAgentSession({cwd:fixture,settingsManager:settings,resourceLoader:loader,modelRuntime:runtime,sessionManager:SessionManager.create(fixture,home+'/sessions'),noTools:'builtin'});
const runner=session.extensionRunner, errors=[];
runner.onError(e=>errors.push(e));
if(!runner.hasHandlers('before_agent_start'))throw new Error('handlers absent');
let promptReads=0;
const custom={type:'before_agent_start',messageType:'custom',message:{role:'custom',customType:'live-probe',content:'operational event'}};
Object.defineProperty(custom,'prompt',{get(){promptReads++;throw new Error('custom event has no user prompt');}});
await runner.emit(custom);
await runner.emit({type:'before_agent_start',messageType:'user',prompt:'Keep this current user request.'});
await runner.emit({type:'before_agent_start',prompt:'Keep this legacy user request.'});
if(promptReads!==0||errors.length)throw new Error(JSON.stringify({promptReads,errors}));
if(!existsSync(home+'/state/.pi-branch-extension-loaded'))throw new Error('branch did not activate against the isolated home');
console.log(JSON.stringify({sdk:'0.99.1',interface:'real AgentSession.extensionRunner.emit',extensions:runner.getExtensionPaths(),customPromptReads:promptReads,userAndLegacyEventsAccepted:true,errors,ownerActivated:true},null,2));
await runner.emit({type:'session_shutdown',reason:'quit'});
await session.dispose();
