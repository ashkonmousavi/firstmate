#!/usr/bin/env bash
# fm-autolaunch-check.sh - throttle check for bin/fm-autolaunch.sh: say when a
# free lane and prepared work sit with no auto-launch decision recorded.
#
# Usage:
#   fm-autolaunch-check.sh          one read-only evaluation (the registered check runs it)
#   fm-autolaunch-check.sh arm      write and register state/autolaunch.check.sh
#   fm-autolaunch-check.sh disarm   remove the check and its registration
#
# RED when all three hold:
#   - bin/fm-capacity.sh --admit reports at least one free lane;
#   - `bin/fm-autolaunch.sh --list-prepared` names at least one item (the
#     launcher's own selection, so the two cannot disagree);
#   - state/autolaunch.log is absent or its last append (the file's mtime) is
#     at least FM_AUTOLAUNCH_STALE_SECS old (default 600: two missed passes).
# Then it prints one `RED auto-launch stalled: ...` line on stdout, which the
# watcher turns into a check wake for this home, and, in a secondmate home,
# also appends it as a `blocked:` line to the parent channel
# (bin/fm-parent-channel-lib.sh fm_parent_channel_report; a main home has none).
# Anything else prints nothing. One stall episode, keyed by the log's mtime
# (or its absence), reports once and then again at most hourly while it
# lasts; the episode marker is state/.autolaunch-check.red and is removed
# when the check goes quiet.
# The check never launches and makes no network call.
# Exit 0 always for an evaluation; arm/disarm exit 1 on failure.
# Test seams with FM_TEST_SEAM=1: FM_AUTOLAUNCH_CAPACITY_BIN (shared with the
# launcher) and FM_AUTOLAUNCH_CHECK_NOW (epoch seconds).
set -u
export LC_ALL=C

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"
export FM_HOME

CHECK_ID=autolaunch
CHECK_SHIM="$STATE/$CHECK_ID.check.sh"
LOG="$STATE/autolaunch.log"
MARKER="$STATE/.autolaunch-check.red"
STALE=${FM_AUTOLAUNCH_STALE_SECS:-600}
case "$STALE" in ''|*[!0-9]*) STALE=600 ;; esac
CAPACITY_BIN="$SCRIPT_DIR/fm-capacity.sh"
NOW=$(date +%s)
if [ "${FM_TEST_SEAM:-}" = 1 ]; then
  CAPACITY_BIN=${FM_AUTOLAUNCH_CAPACITY_BIN:-$CAPACITY_BIN}
  NOW=${FM_AUTOLAUNCH_CHECK_NOW:-$NOW}
fi

mtime() {
  if [ "$(uname)" = Darwin ]; then stat -f %m "$1" 2>/dev/null; else stat -c %Y "$1" 2>/dev/null; fi
}

action_arm() {
  local home tmp
  case "$FM_HOME" in
    /*) home=$FM_HOME ;;
    *) home=$(CDPATH='' cd -- "$FM_HOME" 2>/dev/null && pwd -P) || { echo "fm-autolaunch-check: cannot resolve FM_HOME" >&2; return 1; } ;;
  esac
  [ -d "$STATE" ] && [ ! -L "$STATE" ] || { echo "fm-autolaunch-check: state directory is unavailable" >&2; return 1; }
  [ ! -L "$CHECK_SHIM" ] || { echo "fm-autolaunch-check: $CHECK_SHIM is a symlink" >&2; return 1; }
  tmp=$(umask 077; mktemp "$STATE/.fm-autolaunch-check.XXXXXX") || return 1
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-autolaunch-check.sh - the auto-launch throttle check shim.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$SCRIPT_DIR/fm-autolaunch-check.sh")" > "$tmp" || { rm -f -- "$tmp"; return 1; }
  if ! chmod 0700 "$tmp" || ! mv -f -- "$tmp" "$CHECK_SHIM"; then
    rm -f -- "$tmp"
    return 1
  fi
  if ! FM_HOME="$home" FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-register.sh" "$CHECK_ID" >/dev/null; then
    rm -f -- "$CHECK_SHIM"
    echo "fm-autolaunch-check: could not register $CHECK_SHIM" >&2
    return 1
  fi
  printf 'armed: state/%s.check.sh\n' "$CHECK_ID"
}

quiet() { rm -f -- "$MARKER"; exit 0; }

evaluate() {
  local cap free prepared count first last age episode prev prev_at line rc=0
  cap=$("$CAPACITY_BIN" --admit 2>/dev/null | sed -n '/^capacity:/{p;q;}')
  free=$(printf '%s\n' "$cap" | sed -n 's/.*[[:space:]]free_lanes=\([0-9][0-9]*\).*/\1/p')
  case "$free" in ''|*[!0-9]*|0) quiet ;; esac
  prepared=$("$SCRIPT_DIR/fm-autolaunch.sh" --list-prepared 2>/dev/null) || quiet
  [ -n "$prepared" ] || quiet
  count=$(printf '%s\n' "$prepared" | grep -c .)
  first=$(printf '%s\n' "$prepared" | head -1)
  if [ -f "$LOG" ]; then
    last=$(mtime "$LOG") || last=
    case "$last" in ''|*[!0-9]*) last=0 ;; esac
    age=$((NOW - last))
    [ "$age" -ge "$STALE" ] || quiet
    episode="log:$last"
    age="last record $((age / 60)) min ago"
  else
    episode=none
    age="no record yet"
  fi
  if [ -f "$MARKER" ]; then
    prev=$(sed -n 1p "$MARKER" 2>/dev/null)
    prev_at=$(sed -n 2p "$MARKER" 2>/dev/null)
    case "$prev_at" in ''|*[!0-9]*) prev_at=0 ;; esac
    if [ "$prev" = "$episode" ] && [ $((NOW - prev_at)) -lt 3600 ]; then
      exit 0
    fi
  fi
  line="RED auto-launch stalled on $(hostname 2>/dev/null || echo this-host): $free free lane(s) and $count prepared item(s) (first: $first) but no launch or refusal record in $((STALE / 60)) min ($age); check the auto-launch schedule and state/autolaunch.log"
  printf '%s\n' "$line"
  # shellcheck source=bin/fm-parent-channel-lib.sh
  . "$SCRIPT_DIR/fm-parent-channel-lib.sh"
  fm_parent_channel_report "$FM_HOME" "$STATE" "blocked: $line" >/dev/null || rc=$?
  case "$rc" in
    0|1) ;;
    *) echo "fm-autolaunch-check: parent delivery failed (exit $rc); will retry" >&2; exit 0 ;;
  esac
  printf '%s\n%s\n' "$episode" "$NOW" > "$MARKER" || echo "fm-autolaunch-check: cannot record stall episode" >&2
  exit 0
}

case "${1:-}" in
  '') evaluate ;;
  arm) action_arm ;;
  disarm)
    FM_STATE_OVERRIDE="$STATE" "$SCRIPT_DIR/fm-check-unregister.sh" "$CHECK_ID" >/dev/null || exit 1
    rm -f -- "$MARKER" || exit 1
    printf 'disarmed: state/%s.check.sh\n' "$CHECK_ID"
    ;;
  -h|--help) sed -n '2,/^set -u/p' "$0" | sed '$d; s/^# \{0,1\}//' ;;
  *) echo 'usage: fm-autolaunch-check.sh [arm|disarm]' >&2; exit 2 ;;
esac
